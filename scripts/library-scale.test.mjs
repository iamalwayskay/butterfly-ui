let server,browser,base
const captures='/tmp/butterfly-task-3'
before(async()=>{server=await createServer({server:{host:'127.0.0.1',port:0}});await server.listen();base=`http://127.0.0.1:${server.httpServer.address().port}`;browser=await chromium.launch({headless:true,...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE?{executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE}:{})});await mkdir(captures,{recursive:true})})
after(async()=>{await browser?.close();await server?.close()})
async function open(t,query='',width=1280){const page=await browser.newPage({viewport:{width,height:900}});page.setDefaultTimeout(4000);const errors=[];page.on('pageerror',e=>errors.push(e.message));t.after(async()=>{await page.close();assert.deepEqual(errors,[])});await page.addInitScript(()=>localStorage.setItem('butterfly-meta-connected','true'));await page.goto(`${base}/app/ads${query}`);await page.getByRole('heading',{name:'My Ads',exact:true}).waitFor();return page}

for(const width of [620,540,390,320])test(`dense mobile creative rows retain media, typography and touch targets at ${width}`,async t=>{
 const page=await open(t,'?fixture-count=12&sort=name',width)
 await page.evaluate(()=>document.fonts.ready)
 const geometry=await page.locator('.library-card-wrap').evaluateAll(nodes=>nodes.map(row=>{
   const media=row.querySelector('.bf-creative-card__media'),box=media.getBoundingClientRect(),title=row.querySelector('h3'),target=row.querySelector('.bf-creative-card__select').getBoundingClientRect()
   const placeholder=media.querySelector('span'),titleLink=title.querySelector('a').getBoundingClientRect()
   return {title:title.textContent,width:box.width,height:box.height,rowHeight:row.getBoundingClientRect().height,border:getComputedStyle(row).borderBottomWidth,fontSize:parseFloat(getComputedStyle(title).fontSize),targetWidth:target.width,targetHeight:target.height,titleTargetWidth:titleLink.width,titleTargetHeight:titleLink.height,placeholderClear:!placeholder||placeholder.getBoundingClientRect().top>=target.bottom}
 }))
 const height=await page.evaluate(()=>document.documentElement.scrollHeight)
 t.diagnostic(JSON.stringify({width,height,rows:geometry.map(row=>({title:row.title,height:row.rowHeight,media:row.width}))}))
 await page.screenshot({path:`${captures}/library-density-${width}-${process.env.BF_DENSITY_PHASE || 'after'}.png`,fullPage:true})
 assert.ok(geometry.every(row=>row.width>=103.5&&row.width<=120.5),'mobile thumbnails remain between 104 and 120px')
 assert.ok(geometry.every(row=>row.border==='1px'),'rows use a full-width divider')
 assert.ok(geometry.every(row=>row.fontSize>=13&&row.targetWidth>=44&&row.targetHeight>=44),'density must not shrink text or selection targets')
 assert.ok(geometry.every(row=>row.titleTargetWidth>=44&&row.titleTargetHeight>=44),'actual title links need 44px touch targets')
 assert.ok(geometry.every(row=>row.placeholderClear),'unavailable-media text must clear the selection control')
 const ordinary=geometry.filter(row=>['Evening Routine — Cut 02','First Drop — Cut 03','Serum Still Life — Cut 01'].includes(row.title))
 assert.ok(ordinary.every(row=>row.rowHeight<=245),JSON.stringify(ordinary))
 assert.ok(geometry.every(row=>row.rowHeight<=285),'even long-name rows remain bounded at narrow widths')
 const baseline={620:4675,540:4535,390:4174,320:4149}[width]
 assert.ok(height<=baseline*.9,`12-item page must reduce the ${baseline}px baseline by at least 10%: ${height}`)
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),width)
})

