  assert.equal(await page.locator('.bf-result-count strong').textContent(),String(count))
  assert.equal(await page.locator('.bf-creative-card').count(),Math.min(12,count))
  const boxes=await page.locator('.bf-creative-card__media').evaluateAll(nodes=>nodes.map(node=>{const r=node.getBoundingClientRect();return {height:r.height,width:r.width,ratio:getComputedStyle(node).aspectRatio}}))
  assert.ok(boxes.every(box=>box.height<=341),JSON.stringify(boxes))
  assert.ok(boxes.every(box=>{const [w,h]=box.ratio.split('/').map(Number);return Math.abs(box.width/box.height-w/h)<.01}))
  assert.equal(await page.locator('.library-grid').evaluate(node=>getComputedStyle(node).gridTemplateColumns.split(' ').length),width===1280?2:1)
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),width)
  await page.screenshot({path:`${captures}/library-${count}-${width}-grid.png`,fullPage:true})
  await page.getByRole('button',{name:'Table',exact:true}).click()
  const rows=page.locator('.bf-data-table tbody tr')
  await rows.first().waitFor()
  assert.equal(await rows.count(),Math.min(12,count))
  assert.equal(await rows.first().locator('.library-table-identity').count(),1)
  const metric=rows.first().locator('td').last()
  assert.match(await metric.textContent(),/purchases|No delivery data/i)
  if((await metric.textContent()).includes('purchases'))assert.match(await metric.textContent(),/Sample Meta.*30 days/)
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),width)
