test('draft-key transitions isolate replacement queues and clear only the saved unload guard',async t=>{
 const page=await open(t,1280)
 const id=await page.evaluate(async()=>{const {addLocalAd}=await import('/src/data/ads.ts');return addLocalAd(new File(['%PDF-1.4'],'Original.pdf',{type:'application/pdf'})).id})
 await page.locator('input[type=file]').setInputFiles('public/brand/kindred-campaign-evening.png')
 await page.getByLabel('Product (optional)',{exact:true}).fill('New upload context')
 const switchTo=async path=>{await page.evaluate(path=>{history.pushState({},'',path);dispatchEvent(new PopStateEvent('popstate'))},path)}
 await switchTo(`/app/add?tab=upload&replace=${id}`)
 await page.getByRole('heading',{name:'Reattach Creative Media',exact:true}).waitFor()
 assert.equal(await page.getByRole('button',{name:'Reattach Media',exact:true}).count(),0,'a replacement must not inherit the new-upload queue')
 await page.locator('input[type=file]').setInputFiles('public/brand/kindred-campaign-serum.png')
 await page.getByRole('link',{name:'Add Ads',exact:true}).first().click()
 assert.equal(await page.getByLabel('Product (optional)',{exact:true}).inputValue(),'New upload context')
 assert.equal(await page.getByRole('button',{name:'Remove kindred-campaign-evening.png',exact:true}).count(),1)
 assert.equal(await page.getByRole('button',{name:'Remove kindred-campaign-serum.png',exact:true}).count(),0)
 await switchTo(`/app/add?tab=upload&replace=${id}`)
 await page.getByRole('button',{name:'Reattach Media',exact:true}).click()
 await page.getByRole('heading',{name:'Media Reattached',exact:true}).waitFor()
 assert.equal(await page.evaluate(()=>{const event=new Event('beforeunload',{cancelable:true});dispatchEvent(event);return event.defaultPrevented}),true,'other unsaved draft remains guarded')
 await page.getByRole('link',{name:'Add Ads',exact:true}).first().click()
 await page.getByRole('button',{name:'Add to Library',exact:true}).click()
 await page.getByRole('heading',{name:'Creative Added',exact:true}).waitFor()
 assert.equal(await page.evaluate(()=>{const event=new Event('beforeunload',{cancelable:true});dispatchEvent(event);return event.defaultPrevented}),false)
 const records=await page.evaluate(()=>JSON.parse(localStorage.getItem('butterfly-local-uploads')))
 assert.equal(records.length,2);assert.ok(records.some(ad=>ad.id===id&&ad.name==='Original.pdf'));assert.equal(records.find(ad=>ad.id!==id).uploadContext.product,'New upload context')
})

