test('every Settings tab is keyboard reachable and fully visible after focus and reload at 390px',async t=>{
  const page=await pageFor(t,390)
  const tabs=page.getByRole('navigation',{name:'Settings sections'})
  await tabs.getByRole('link',{name:'Sources',exact:true}).focus()
  await page.waitForFunction(el=>getComputedStyle(el,'::after').opacity==='1',await tabs.elementHandle())
  for(const name of ['Sources','Analysis Properties','Workspace','Profile']){
    if(name!=='Sources')await page.keyboard.press('Tab')
    const tab=tabs.getByRole('link',{name,exact:true})
    assert.equal(await tab.evaluate(el=>el===document.activeElement),true)
    assert.equal(await tab.evaluate(el=>{const rect=el.getBoundingClientRect(),parent=el.parentElement.getBoundingClientRect();return rect.left>=parent.left-1&&rect.right<=parent.right+1&&rect.right<=innerWidth}),true)
    assert.equal(await tab.evaluate(el=>{const rect=el.getBoundingClientRect();return rect.width>=44&&rect.height>=44}),true)
  }
  await page.waitForFunction(el=>getComputedStyle(el,'::before').opacity==='1',await tabs.elementHandle())
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
  await page.keyboard.press('Enter')
  await page.waitForURL(/tab=profile/)
  await page.goto(base+'/settings?tab=sources')
  await page.goto(base+'/settings?tab=profile')
  await page.reload()
  const active=tabs.getByRole('link',{name:'Profile',exact:true})
  await active.waitFor()
  assert.equal(await active.evaluate(el=>{const rect=el.getBoundingClientRect(),parent=el.parentElement.getBoundingClientRect();return rect.left>=parent.left-1&&rect.right<=parent.right+1&&rect.right<=innerWidth}),true)
  await page.setViewportSize({width:1280,height:900})
  await page.reload()
  await page.waitForFunction(el=>getComputedStyle(el,'::before').opacity==='0'&&getComputedStyle(el,'::after').opacity==='0',await tabs.elementHandle())
  assert.equal(await tabs.locator('.bf-page-tabs__scroll').evaluate(el=>el.scrollLeft),0)
  assert.equal(await active.evaluate(el=>el.getBoundingClientRect().right<=innerWidth),true)
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
})
