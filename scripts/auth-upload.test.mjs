async function pageFor(t,path,authenticated=!path.startsWith("/login")) {
  const context=await browser.newContext(); const page=await context.newPage(); const errors=[]
  page.setDefaultTimeout(3000)
  page.on("pageerror",error=>errors.push(error.message))
  if(authenticated)await context.addInitScript(()=>{if(!sessionStorage.getItem("auth-seeded")){localStorage.setItem("butterfly-fixture-authenticated","true");sessionStorage.setItem("auth-seeded","true")}})
  t.after(async()=>{await context.close();assert.deepEqual(errors,[])})
  await page.goto(base+path)
  return page
}
